/// Whether [locale] (already in underscore form) is a recognised locale.
///
/// A language from the list is accepted with any region, and with any known
/// script plus any region.
bool isKnownLocale(String locale) {
  final normalized = locale.replaceAll('-', '_');
  if (_knownLocales.contains(normalized)) return true;

  final parts = normalized.split('_');
  switch (parts.length) {
    case 1:
      return _knownLocales.contains(parts[0]);
    case 2:
      return _knownLocales.contains(parts[0]);
    case 3:
      if (_knownLocales.contains(parts[0]) &&
          _knownScripts.contains(parts[1])) {
        return true;
      }
      return false;
    default:
      return false;
  }
}
